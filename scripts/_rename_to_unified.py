def process(fname):
    with open(fname, 'r', encoding='utf-8') as f:
        html = f.read()

    for old, new in RENAME.items():
        old_esc = re.escape(old)
        # 1) CSS selector: .oldclass → .newclass (but NOT inside CSS property values)
        html = re.sub(r'(?<=[\s,])\.' + old_esc + r'(?=[^{}]*\{)', new, html)
        # 2) Also replace in remaining .old anywhere as selector
        html = re.sub(r'(?<!\w)\.' + old_esc + r'\b', new, html)
        # 3) HTML class="old" / class="... old ..."
        html = html.replace(f'"{old}"', f'"{new.strip(".")}"')
        # inline classNames in JS strings
        html = html.replace(f"'{old}'", f"'{new.strip(".")}'")
        # 4) bare class name used by JS: className += " guzhen-hero" etc
        html = re.sub(r'\b' + re.escape(old.lstrip('.')) + r'\b', new.lstrip('.'), html)

    # prepend channel.css link if not present
    if 'css/channel.css' not in html:
        link = '<link rel="stylesheet" href="css/channel.css?v=20261016d">'
        html = html.replace('</head>', link + '\n</head>', 1)

    with open(fname, 'w', encoding='utf-8') as f:
        f.write(html)
    print(f'  OK {os.path.basename(fname)}')

